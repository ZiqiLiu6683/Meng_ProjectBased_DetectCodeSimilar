#!/usr/bin/env python3
"""Generate long Java evaluation pairs for size-stress testing.

The short handcrafted dataset is useful for targeted behavior checks, but most
files are only 5-27 lines. This generator creates longer single-file Java
programs while preserving labeled clone transformations.
"""

from __future__ import annotations

import csv
import shutil
from dataclasses import dataclass
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "evaluation" / "samples" / "java_long"
PAIRS_CSV = ROOT / "evaluation" / "long_pairs.csv"
README = OUT_DIR / "README.md"


@dataclass(frozen=True)
class Domain:
    slug: str
    label: str
    noun: str
    item: str
    token: str
    high: int
    medium: int
    low: int
    bonus_word: str
    region_word: str


DOMAINS = [
    Domain("order", "OrderRisk", "order", "amount", "email", 90, 45, 12, "vip", "CN"),
    Domain("sensor", "SensorQuality", "sensor", "reading", "device", 85, 40, 10, "calibrated", "LAB"),
    Domain("invoice", "InvoiceAudit", "invoice", "charge", "memo", 120, 60, 15, "priority", "EU"),
    Domain("student", "StudentProfile", "student", "score", "note", 95, 70, 30, "honor", "ONLINE"),
    Domain("shipment", "ShipmentPlan", "shipment", "weight", "route", 110, 55, 20, "express", "AIR"),
    Domain("ticket", "TicketReview", "ticket", "duration", "message", 75, 35, 8, "urgent", "REMOTE"),
]


HEADER = [
    "project",
    "pair_id",
    "language",
    "file_a",
    "file_b",
    "expected_type",
    "expected_scope",
    "transformation_tag",
    "difficulty",
    "expected_behavior",
    "limitation_tag",
    "notes",
]


def main() -> None:
    if OUT_DIR.exists():
        shutil.rmtree(OUT_DIR)
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    rows: list[dict[str, str]] = []
    for index, domain in enumerate(DOMAINS, start=1):
        rows.extend(generate_domain_pairs(domain, index))

    with PAIRS_CSV.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=HEADER)
        writer.writeheader()
        writer.writerows(rows)

    README.write_text(
        "# Long Java Evaluation Dataset\n\n"
        "Generated by `scripts/build_long_code_dataset.py`.\n\n"
        "- 36 labeled Java pairs.\n"
        "- 72 Java files.\n"
        "- Target size: roughly 180-230 lines per file, which is more than 10x the current short samples.\n"
        "- Covers T1, T2, T3, inline-to-helper, call-chain refactor, and non-clone stress cases.\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(rows)} pairs to {PAIRS_CSV}")
    print(f"Wrote Java files to {OUT_DIR}")


def generate_domain_pairs(domain: Domain, index: int) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []

    pairs = [
        (
            "LongT1",
            f"java_long_t1_{domain.slug}_{index:02d}",
            "T1",
            "FULL",
            "CONTROL_FLOW_REORDER",
            "L2",
            "Should detect a long near-identical clone with comment and spacing changes.",
            "",
            "Long exact-style clone; comments and formatting differ.",
            render_score_class(domain, "A", style="base", rename=False),
            render_score_class(domain, "A", style="commented", rename=False),
        ),
        (
            "LongT2",
            f"java_long_t2_{domain.slug}_{index:02d}",
            "T2",
            "FULL",
            "RENAMING",
            "L2",
            "Should detect a long renamed clone.",
            "THRESHOLDS_HEURISTIC",
            "Long class with renamed class, methods, parameters, and locals.",
            render_score_class(domain, "A", style="base", rename=False),
            render_score_class(domain, "B", style="base", rename=True),
        ),
        (
            "LongT3",
            f"java_long_t3_{domain.slug}_{index:02d}",
            "T3",
            "FULL",
            "STATEMENT_INSERT_DELETE",
            "L3",
            "Should detect a long modified clone with added branches and threshold changes.",
            "THRESHOLDS_HEURISTIC",
            "Long Type-3 clone with guard insertion and scoring edits.",
            render_score_class(domain, "A", style="base", rename=False),
            render_score_class(domain, "C", style="t3", rename=True),
        ),
        (
            "LongInternalHelper",
            f"java_long_helper_{domain.slug}_{index:02d}",
            "T4_WEAK",
            "FULL",
            "INLINE_TO_HELPER",
            "L3",
            "Should keep evidence when repeated inline checks are moved into helpers.",
            "CALL_GRAPH_NOT_EXPANDED",
            "Long inline-to-helper extraction case.",
            render_score_class(domain, "A", style="inline", rename=False),
            render_score_class(domain, "D", style="helper", rename=True),
        ),
        (
            "LongCallChain",
            f"java_long_call_chain_{domain.slug}_{index:02d}",
            "T4_WEAK",
            "MIXED",
            "CALL_CHAIN_REFACTOR",
            "L4",
            "Should expose whether a long call-chain refactor remains connected.",
            "CALL_GRAPH_NOT_EXPANDED",
            "Main workflow is split into staged internal calls.",
            render_score_class(domain, "A", style="inline", rename=False),
            render_score_class(domain, "E", style="chain", rename=True),
        ),
        (
            "LongNonClone",
            f"java_long_nonclone_{domain.slug}_{index:02d}",
            "NON_CLONE",
            "UNKNOWN",
            "UNRELATED",
            "L3",
            "Should reject long unrelated programs with generic loop/API overlap.",
            "THRESHOLDS_HEURISTIC",
            "Both files are long and loop-heavy but solve different problems.",
            render_score_class(domain, "A", style="base", rename=False),
            render_unrelated_class(domain, "Z"),
        ),
    ]

    for project, pair_id, expected_type, expected_scope, tag, difficulty, behavior, limitation, notes, left, right in pairs:
        left_name = f"{pair_id}_A.java"
        right_name = f"{pair_id}_B.java"
        write_file(OUT_DIR / left_name, left)
        write_file(OUT_DIR / right_name, right)
        rows.append({
            "project": project,
            "pair_id": pair_id,
            "language": "JAVA",
            "file_a": f"samples/java_long/{left_name}",
            "file_b": f"samples/java_long/{right_name}",
            "expected_type": expected_type,
            "expected_scope": expected_scope,
            "transformation_tag": tag,
            "difficulty": difficulty,
            "expected_behavior": behavior,
            "limitation_tag": limitation,
            "notes": notes,
        })
    return rows


def write_file(path: Path, text: str) -> None:
    path.write_text(text.rstrip() + "\n", encoding="utf-8")


def render_score_class(domain: Domain, suffix: str, style: str, rename: bool) -> str:
    cls = f"{domain.label}{suffix}"
    main_name = "evaluate" if not rename else "compute"
    values = "values" if not rename else "entries"
    labels = "labels" if not rename else "tokens"
    region = "region" if not rename else "zone"
    limit = "limit" if not rename else "cap"
    total = "total" if not rename else "score"
    item = domain.item if not rename else f"{domain.item}Value"
    token = domain.token if not rename else f"{domain.token}Text"
    high = domain.high + (3 if style == "t3" else 0)
    medium = domain.medium + (2 if style == "t3" else 0)
    low = domain.low
    comment = "// Long T1 comment variant.\n" if style == "commented" else ""

    helper_condition = (
        f"isImportant{domain.label}Value({item})"
        if style in {"helper", "chain"}
        else f"{item} >= {medium} && {item} <= {high}"
    )
    extra_guard = (
        f"""
            if ({item} == {low}) {{
                subtotal += 1;
            }}
"""
        if style == "t3"
        else ""
    )

    main_body = (
        f"""
    int {main_name}(int[] {values}, String[] {labels}, String {region}, int {limit}) {{
        int {total} = 0;
        {total} += score{domain.label}Values({values}, {limit});
        {total} += score{domain.label}Labels({labels});
        {total} += score{domain.label}Region({region});
        {total} += rollingAdjustment({values});
        {total} += checksumBonus({labels}, {region});
        {total} -= penaltyForGaps({values});
        return clampScore({total}, {limit});
    }}
"""
        if style != "chain"
        else f"""
    int {main_name}(int[] {values}, String[] {labels}, String {region}, int {limit}) {{
        int stageOne = collectNumericEvidence({values}, {limit});
        int stageTwo = collectTextEvidence({labels}, {region});
        int stageThree = collectStabilityEvidence({values}, {labels});
        return clampScore(stageOne + stageTwo + stageThree, {limit});
    }}

    private int collectNumericEvidence(int[] {values}, int {limit}) {{
        int result = score{domain.label}Values({values}, {limit});
        result += rollingAdjustment({values});
        result -= penaltyForGaps({values});
        return result;
    }}

    private int collectTextEvidence(String[] {labels}, String {region}) {{
        return score{domain.label}Labels({labels}) + score{domain.label}Region({region});
    }}

    private int collectStabilityEvidence(int[] {values}, String[] {labels}) {{
        return checksumBonus({labels}, "{domain.region_word}") + trendWeight({values});
    }}
"""
    )

    return f"""
{comment}class {cls} {{
{main_body}
    private int score{domain.label}Values(int[] {values}, int {limit}) {{
        int subtotal = 0;
        if ({values} == null || {values}.length == 0) {{
            return 0;
        }}
        for (int index = 0; index < {values}.length; index++) {{
            int {item} = {values}[index];
            if ({item} < 0) {{
                subtotal -= 4;
                continue;
            }}
            if ({helper_condition}) {{
                subtotal += 9;
            }} else if ({item} > {low}) {{
                subtotal += 3;
            }} else {{
                subtotal += 1;
            }}
{extra_guard}            if (index % 4 == 0 && {item} > {limit}) {{
                subtotal += 2;
            }}
        }}
        return subtotal;
    }}

    private int score{domain.label}Labels(String[] {labels}) {{
        int subtotal = 0;
        if ({labels} == null) {{
            return subtotal;
        }}
        for (String {token} : {labels}) {{
            String normalized = normalizeToken({token});
            if (normalized.isEmpty()) {{
                subtotal -= 1;
            }} else if (normalized.contains("{domain.bonus_word}")) {{
                subtotal += 7;
            }} else if (normalized.length() > 8) {{
                subtotal += 2;
            }} else {{
                subtotal += 1;
            }}
        }}
        return subtotal;
    }}

    private int score{domain.label}Region(String {region}) {{
        String normalized = normalizeToken({region});
        if (normalized.equals("{domain.region_word.lower()}")) {{
            return 6;
        }}
        if (normalized.startsWith("remote") || normalized.startsWith("test")) {{
            return 3;
        }}
        return normalized.isEmpty() ? -2 : 1;
    }}

    private int rollingAdjustment(int[] {values}) {{
        if ({values} == null || {values}.length < 3) {{
            return 0;
        }}
        int adjustment = 0;
        int previous = {values}[0];
        for (int i = 1; i < {values}.length; i++) {{
            int current = {values}[i];
            if (current > previous) {{
                adjustment += 1;
            }} else if (current + 5 < previous) {{
                adjustment -= 1;
            }}
            previous = current;
        }}
        return adjustment;
    }}

    private int penaltyForGaps(int[] {values}) {{
        if ({values} == null) {{
            return 0;
        }}
        int penalty = 0;
        for (int i = 1; i < {values}.length; i++) {{
            int gap = Math.abs({values}[i] - {values}[i - 1]);
            if (gap > {high}) {{
                penalty += 5;
            }} else if (gap > {medium}) {{
                penalty += 2;
            }}
        }}
        return penalty;
    }}

    private int trendWeight(int[] {values}) {{
        if ({values} == null || {values}.length == 0) {{
            return 0;
        }}
        int rising = 0;
        int falling = 0;
        for (int i = 1; i < {values}.length; i++) {{
            if ({values}[i] >= {values}[i - 1]) {{
                rising++;
            }} else {{
                falling++;
            }}
        }}
        return rising >= falling ? 2 : -2;
    }}

    private int checksumBonus(String[] {labels}, String {region}) {{
        int checksum = 17;
        if ({labels} != null) {{
            for (String {token} : {labels}) {{
                checksum = checksum * 31 + normalizeToken({token}).length();
            }}
        }}
        checksum = checksum * 31 + normalizeToken({region}).length();
        return Math.abs(checksum % 5);
    }}

    private int distributionScore(int[] {values}) {{
        if ({values} == null || {values}.length == 0) {{
            return 0;
        }}
        int below = 0;
        int middle = 0;
        int above = 0;
        for (int {item} : {values}) {{
            if ({item} < {low}) {{
                below++;
            }} else if ({item} <= {medium}) {{
                middle++;
            }} else {{
                above++;
            }}
        }}
        if (above > middle && above > below) {{
            return 4;
        }}
        if (middle >= below) {{
            return 2;
        }}
        return -1;
    }}

    private boolean hasStableWindow(int[] {values}, int window) {{
        if ({values} == null || {values}.length < window || window <= 1) {{
            return false;
        }}
        for (int start = 0; start <= {values}.length - window; start++) {{
            int min = {values}[start];
            int max = {values}[start];
            for (int offset = 1; offset < window; offset++) {{
                int current = {values}[start + offset];
                if (current < min) {{
                    min = current;
                }}
                if (current > max) {{
                    max = current;
                }}
            }}
            if (max - min <= {low}) {{
                return true;
            }}
        }}
        return false;
    }}

    String explain{domain.label}Score(int[] {values}, String[] {labels}, String {region}) {{
        StringBuilder builder = new StringBuilder();
        builder.append("distribution=").append(distributionScore({values}));
        builder.append(", trend=").append(trendWeight({values}));
        builder.append(", stable=").append(hasStableWindow({values}, 3));
        builder.append(", text=").append(score{domain.label}Labels({labels}));
        builder.append(", region=").append(score{domain.label}Region({region}));
        return builder.toString();
    }}

    private String normalizeToken(String {token}) {{
        if ({token} == null) {{
            return "";
        }}
        String trimmed = {token}.trim().toLowerCase();
        StringBuilder builder = new StringBuilder();
        for (int i = 0; i < trimmed.length(); i++) {{
            char ch = trimmed.charAt(i);
            if (Character.isLetterOrDigit(ch)) {{
                builder.append(ch);
            }}
        }}
        return builder.toString();
    }}

    private int clampScore(int value, int {limit}) {{
        int upper = Math.max(10, {limit});
        if (value < 0) {{
            return 0;
        }}
        if (value > upper) {{
            return upper;
        }}
        return value;
    }}

    private boolean isImportant{domain.label}Value(int {item}) {{
        return {item} >= {medium} && {item} <= {high};
    }}
}}
"""


def render_unrelated_class(domain: Domain, suffix: str) -> str:
    cls = f"{domain.label}Unrelated{suffix}"
    return f"""
class {cls} {{
    String renderReport(String[] rows, int width) {{
        StringBuilder builder = new StringBuilder();
        int lineNumber = 1;
        if (rows == null || rows.length == 0) {{
            return "";
        }}
        for (String row : rows) {{
            String cleaned = cleanRow(row);
            if (cleaned.isEmpty()) {{
                continue;
            }}
            builder.append(padLeft(lineNumber, 4));
            builder.append(" | ");
            builder.append(wrap(cleaned, width));
            builder.append("\\n");
            lineNumber++;
        }}
        return builder.toString();
    }}

    private String cleanRow(String row) {{
        if (row == null) {{
            return "";
        }}
        String trimmed = row.trim();
        StringBuilder builder = new StringBuilder();
        boolean previousSpace = false;
        for (int i = 0; i < trimmed.length(); i++) {{
            char ch = trimmed.charAt(i);
            if (Character.isWhitespace(ch)) {{
                if (!previousSpace) {{
                    builder.append(' ');
                }}
                previousSpace = true;
            }} else if (ch != '#') {{
                builder.append(ch);
                previousSpace = false;
            }}
        }}
        return builder.toString();
    }}

    private String wrap(String text, int width) {{
        int safeWidth = Math.max(12, width);
        StringBuilder builder = new StringBuilder();
        int column = 0;
        for (String word : text.split(" ")) {{
            if (column + word.length() > safeWidth) {{
                builder.append("\\n    ");
                column = 4;
            }}
            builder.append(word).append(' ');
            column += word.length() + 1;
        }}
        return builder.toString().trim();
    }}

    private String padLeft(int value, int size) {{
        String text = String.valueOf(value);
        StringBuilder builder = new StringBuilder();
        for (int i = text.length(); i < size; i++) {{
            builder.append('0');
        }}
        builder.append(text);
        return builder.toString();
    }}

    int countWords(String[] rows) {{
        int count = 0;
        if (rows == null) {{
            return count;
        }}
        for (String row : rows) {{
            String cleaned = cleanRow(row);
            if (!cleaned.isEmpty()) {{
                count += cleaned.split(" ").length;
            }}
        }}
        return count;
    }}

    int longestLine(String[] rows) {{
        int max = 0;
        if (rows == null) {{
            return max;
        }}
        for (String row : rows) {{
            String cleaned = cleanRow(row);
            if (cleaned.length() > max) {{
                max = cleaned.length();
            }}
        }}
        return max;
    }}

    boolean containsPhrase(String[] rows, String phrase) {{
        String needle = cleanRow(phrase).toLowerCase();
        if (needle.isEmpty() || rows == null) {{
            return false;
        }}
        for (String row : rows) {{
            if (cleanRow(row).toLowerCase().contains(needle)) {{
                return true;
            }}
        }}
        return false;
    }}

    String[] filterRows(String[] rows, int minLength) {{
        if (rows == null) {{
            return new String[0];
        }}
        String[] scratch = new String[rows.length];
        int size = 0;
        for (String row : rows) {{
            String cleaned = cleanRow(row);
            if (cleaned.length() >= minLength) {{
                scratch[size] = cleaned;
                size++;
            }}
        }}
        String[] result = new String[size];
        for (int i = 0; i < size; i++) {{
            result[i] = scratch[i];
        }}
        return result;
    }}

    int countLinesWithDigits(String[] rows) {{
        int count = 0;
        if (rows == null) {{
            return count;
        }}
        for (String row : rows) {{
            String cleaned = cleanRow(row);
            for (int i = 0; i < cleaned.length(); i++) {{
                if (Character.isDigit(cleaned.charAt(i))) {{
                    count++;
                    break;
                }}
            }}
        }}
        return count;
    }}

    String buildIndex(String[] rows) {{
        StringBuilder builder = new StringBuilder();
        String[] filtered = filterRows(rows, 3);
        for (int i = 0; i < filtered.length; i++) {{
            builder.append(padLeft(i + 1, 3));
            builder.append(':');
            builder.append(filtered[i].length());
            builder.append(';');
        }}
        return builder.toString();
    }}

    int estimateWrappedLineCount(String[] rows, int width) {{
        int lines = 0;
        if (rows == null) {{
            return lines;
        }}
        int safeWidth = Math.max(12, width);
        for (String row : rows) {{
            String cleaned = cleanRow(row);
            if (cleaned.isEmpty()) {{
                continue;
            }}
            lines += Math.max(1, (cleaned.length() + safeWidth - 1) / safeWidth);
        }}
        return lines;
    }}

    String summarize(String[] rows) {{
        int words = countWords(rows);
        int longest = longestLine(rows);
        boolean hasWarning = containsPhrase(rows, "warning");
        int digitLines = countLinesWithDigits(rows);
        int wrapped = estimateWrappedLineCount(rows, 40);
        StringBuilder builder = new StringBuilder();
        builder.append("words=").append(words);
        builder.append(", longest=").append(longest);
        builder.append(", digits=").append(digitLines);
        builder.append(", wrapped=").append(wrapped);
        builder.append(", warning=").append(hasWarning);
        builder.append(", index=").append(buildIndex(rows));
        return builder.toString();
    }}
}}
"""


if __name__ == "__main__":
    main()
